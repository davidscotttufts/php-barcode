    #[DataProvider('references')]
    public function testMatchesZint(string $data, string $expected): void
    {
        $label = (string) $this->dataName();
        $symbol = self::symbology($label)->encode($data);

        self::assertInstanceOf(LinearSymbol::class, $symbol);
        self::assertSame($expected, $symbol->toBinary());
    }

    private static function symbology(string $label): S\SymbologyInterface
    {
        return match ($label) {
            'ean13', 'ean13 + ean5' => new S\Ean13(),
            'ean8' => new S\Ean8(),
            'upca', 'upca + ean2' => new S\UpcA(),
            'upce ns0', 'upce ns1', 'upce + ean5' => new S\UpcE(),
            'itf14' => new S\Itf14(S\BearerBars::None),
            'code93' => new S\Code93(),
            'code93 full ascii' => new S\Code93(fullAscii: true),
            'code39 extended' => new S\Code39Extended(wideRatio: 2),
            'code11 two checks' => new S\Code11(2),
            'code11 one check' => new S\Code11(1),
            'code11 no check' => new S\Code11(0),
            'msi none' => new S\MsiPlessey(S\MsiChecksum::None),
            'msi mod10' => new S\MsiPlessey(S\MsiChecksum::Mod10),
            'msi mod1010' => new S\MsiPlessey(S\MsiChecksum::Mod1010),
            'msi mod11', 'msi mod11 ten' => new S\MsiPlessey(S\MsiChecksum::Mod11),
            'msi mod1110' => new S\MsiPlessey(S\MsiChecksum::Mod1110),
            'msi mod11 ncr' => new S\MsiPlessey(S\MsiChecksum::Mod11, ncrWeights: true),
            'industrial' => new S\Industrial2of5(),
            'industrial check' => new S\Industrial2of5(withChecksum: true),
            'iata' => new S\Iata2of5(),
            'pharmacode', 'pharmacode max' => new S\Pharmacode(),
            'plessey' => new S\Plessey(),
            'telepen' => new S\Telepen(),
            'telepen numeric', 'telepen numeric X' => new S\Telepen(numeric: true),
            'code32' => new S\Code32(wideRatio: 2),
            'pzn' => new S\Pzn(wideRatio: 2),
            default => throw new \LogicException("No symbology for {$label}"),
        };
    }
